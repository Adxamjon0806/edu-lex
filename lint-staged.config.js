// pre-commit запускает lint-staged с --concurrent false (причина — в .husky/pre-commit): ключи выполняются
// по очереди в порядке объявления, поэтому tsc, Steiger и Vitest из последнего ключа читают файлы,
// уже отформатированные Prettier.
// Шаблоны для Prettier не пересекаются, чтобы каждый файл форматировался один раз.
/** @type {import('lint-staged').Configuration} */
export default {
  // Форматируем все индексированные файлы, кроме проверяемых ESLint; неподдерживаемые Prettier пропускаем без ошибки.
  // Prettier здесь и ниже запускаем без --cache: ключ кэша не учитывает плагины и тему Tailwind,
  // и после их изменения файл считался бы уже отформатированным.
  '!(*.{cjs,js,json,json5,jsonc,mjs,ts,tsx,yaml,yml})': ['prettier --ignore-unknown --write'],
  // Сначала форматируем JS/TS, JSON и YAML, затем блокируем коммит при любой ошибке или предупреждении ESLint.
  // --no-warn-ignored: исключённые из ESLint файлы (generatedRouteTree.ts, pnpm-lock.yaml) иначе дают предупреждение
  // «File ignored», и --max-warnings 0 блокирует коммит.
  '*.{cjs,js,json,json5,jsonc,mjs,ts,tsx,yaml,yml}': ['prettier --write', 'eslint --max-warnings 0 --no-warn-ignored'],
  // Функции не передают список индексированных файлов: этим командам он не нужен. Строке vitest список передаётся.
  // Ключ срабатывает, только если в индексе есть добавленные или изменённые TS-файлы: коммит из одних удалений
  // или не-TS файлов проходит без проверки типов, архитектуры и тестов; их проверяет pnpm check.
  '*.{ts,tsx}': [
    // Перегенерируем дерево маршрутов и проверяем типы всего проекта по tsconfig. pre-commit запускает lint-staged
    // с --hide-unstaged: неиндексированные изменения отслеживаемых файлов спрятаны, поэтому проверяется то,
    // что попадёт в коммит. Неотслеживаемые файлы не прячутся, поэтому новые файлы маршрутов вне индекса
    // тоже попадут в генерацию: добавляй их в индекс, иначе в коммит попадёт дерево маршрутов со ссылкой
    // на файл вне коммита.
    () => 'pnpm types:check',
    // Блокируем коммит, если дерево маршрутов изменилось после генерации:
    // его нужно добавить в коммит вместе с маршрутами.
    () => 'git diff --exit-code -- src/app/router/generatedRouteTree.ts',
    // Проверяем архитектуру FSD во всём src: нарушение может появиться и в неизменённых файлах.
    () => 'pnpm arch:check',
    // Запускаем только тесты, которые зависят от индексированных файлов; отсутствие таких тестов не ошибка.
    'vitest related --run --passWithNoTests',
  ],
}
